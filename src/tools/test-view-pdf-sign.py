#!/usr/bin/env python3
"""Make a genuine detached CMS-signed synthetic PDF with standard OpenSSL.

Only fixtures generated by test-view-pdf are read. No verification implementation
is supplied to the production module: the installed MuPDF lacks a PKCS7 backend.
OpenSSL independently checks fixture byte ranges before and after a consented
incremental save, and detects a deliberately corrupted signed byte.
"""
import pathlib
import re
import subprocess
import sys

root = pathlib.Path(sys.argv[1])
mode = sys.argv[2]


def run(*args):
    return subprocess.run(args, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)


def ranges(data):
    m = re.search(rb"/ByteRange\s*\[\s*(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s*\]", data)
    if not m:
        raise RuntimeError("generated signature has no ByteRange")
    return m, list(map(int, m.groups()))


if mode == "make":
    data = bytearray((root / "signature-placeholder.pdf").read_bytes())
    match = re.search(rb"/Contents\s*(<[0-9a-fA-F]+>)", data)
    if not match:
        raise RuntimeError("generated signature has no hex Contents")
    start, end = match.span(1)
    br, _ = ranges(data)
    replacement = f"/ByteRange [0 {start} {end} {len(data)-end}]".encode()
    if len(replacement) > br.end() - br.start():
        raise RuntimeError("ByteRange reservation too small")
    data[br.start():br.end()] = replacement.ljust(br.end() - br.start(), b" ")
    signed_bytes = data[:start] + data[end:]
    (root / "signed-bytes.bin").write_bytes(signed_bytes)
    run("openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "1",
        "-subj", "/CN=Generated test signer/O=LOCachy tests", "-keyout", str(root / "key.pem"), "-out", str(root / "cert.pem"))
    run("openssl", "cms", "-sign", "-binary", "-md", "sha256", "-in", str(root / "signed-bytes.bin"),
        "-signer", str(root / "cert.pem"), "-inkey", str(root / "key.pem"), "-outform", "DER", "-out", str(root / "cms.der"))
    cms = (root / "cms.der").read_bytes().hex().encode()
    if len(cms) > end - start - 2:
        raise RuntimeError("CMS reservation too small")
    data[start + 1:end - 1] = cms.ljust(end - start - 2, b"0")
    (root / "signed.pdf").write_bytes(data)
    run("openssl", "cms", "-verify", "-binary", "-inform", "DER", "-in", str(root / "cms.der"),
        "-content", str(root / "signed-bytes.bin"), "-CAfile", str(root / "cert.pem"), "-out", "/dev/null")
    print("PASS generated CMS fixture verifies with explicit generated test trust anchor")
else:
    original = (root / "signed.pdf").read_bytes()
    saved = (root / "signed-consented.pdf").read_bytes()
    if not saved.startswith(original):
        raise RuntimeError("snapshot did not retain exact signed original prefix")
    _, (a, n, b, m) = ranges(saved)
    (root / "saved-signed-bytes.bin").write_bytes(saved[a:a+n] + saved[b:b+m])
    run("openssl", "cms", "-verify", "-binary", "-inform", "DER", "-in", str(root / "cms.der"),
        "-content", str(root / "saved-signed-bytes.bin"), "-CAfile", str(root / "cert.pem"), "-out", "/dev/null")
    corrupt = bytearray(saved[a:a+n] + saved[b:b+m])
    corrupt[8] ^= 1
    (root / "corrupt-signed-bytes.bin").write_bytes(corrupt)
    bad = subprocess.run(["openssl", "cms", "-verify", "-binary", "-inform", "DER", "-in", str(root / "cms.der"),
                          "-content", str(root / "corrupt-signed-bytes.bin"), "-noverify", "-out", "/dev/null"],
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if bad.returncode == 0:
        raise RuntimeError("corrupted digest incorrectly accepted")
    print("PASS OpenSSL: signed original prefix/digest retained; corrupted signed bytes rejected (not document certification approval)")
